import os
import pandas as pd
import argparse

# %% Argparse preamble
parser = argparse.ArgumentParser(
    description="Amend the annotations in the TAB file produced by 'snippy-vcf_to_tab' to the corresponding filtered bedMethyl TSV file"
)
parser.add_argument("input1", help="Path to the filtered bedMethyl TSV file of interest")
parser.add_argument("input2", help="Path to the corresponding TAB file generated by 'snippy-vcf_to_tab'")
args = parser.parse_args()

# %% Import the two input arguments into DataFrames
tsv_df = pd.read_csv(args.input1, sep='\t')
tab_df = pd.read_csv(args.input2, sep='\t')

# %% Pull only the columns needed for annotation
annotation_df = tab_df[['POS', 'LOCUS_TAG', 'GENE', 'PRODUCT']]

# %% Merge annotations onto the TSV dataframe
tsv_df = tsv_df.merge(
    annotation_df,
    left_on='Position',
    right_on='POS',
    how='left'
)

# %% Clean up column names
tsv_df = tsv_df.rename(columns={
    'LOCUS_TAG': 'Locus_tag',
    'GENE': 'Gene',
    'PRODUCT': 'Product'
})

# Remove the duplicate key column from TAB
tsv_df = tsv_df.drop(columns='POS')

# %% Export the annotated TSV file
tsv_df.to_csv(
    'annotated_table_' + os.path.splitext(os.path.basename(args.input1))[0] + '.tsv',
    sep='\t',
    index=False
)